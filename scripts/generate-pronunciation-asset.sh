#!/usr/bin/env bash
# Requires local phonon:latest, Ollama, FFmpeg, and a built stdo binary.
set -euo pipefail
cd "$(dirname "$0")/.."
export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
stdo_bin=${STDO_BIN:-./target/release/stdo}
if [[ ! -x "$stdo_bin" ]]; then
  cargo build --locked --release
fi
command -v ollama >/dev/null
command -v ffmpeg >/dev/null
mkdir -p assets
stage=$(mktemp -d assets/.pronunciation.XXXXXX)
trap 'rm -rf "$stage"' EXIT
cat > "$stage/workflow.yaml" <<'YAML'
version: "1.0"
name: stdo-pronunciation
inputs:
  stage: { type: path }
steps:
  - id: pronunciation
    cmd:
      - printf
      - '%s\n'
      - 'Quick question: how do you actually pronounce this tool? The docs say S. T. D. O., or studio... but honestly, every local AI model just calls it steedo. By the way, this audio was generated by a three-step pipeline in S. T. D. O. ... I mean steedo ... wait, no, studio!'
  - id: phonon
    cmd: [ollama, run, 'phonon:latest']
    pipe_from: pronunciation
    capture_stdout: false
  - id: waveform
    cmd:
      - sh
      - -c
      - |
        set -eu
        cat > "$1/stdo-pronunciation.wav"
        ffmpeg -nostdin -hide_banner -loglevel error -y \
          -f lavfi -i 'color=c=0x0d1117:s=1280x720:r=30' \
          -i "$1/stdo-pronunciation.wav" \
          -filter_complex '[1:a]aformat=channel_layouts=mono,compand,showwaves=s=1280x720:mode=cline:rate=30:scale=sqrt:colors=0x38bdf8[fg];[0:v][fg]overlay=format=auto,format=yuv420p[v]' \
          -map '[v]' -map 1:a:0 -c:v libx264 -crf 28 -preset veryslow -maxrate 60k -bufsize 60k \
          -pix_fmt yuv420p -c:a aac -ac 1 -b:a 32k -shortest -movflags +faststart \
          "$1/stdo-pronunciation.mp4"
      - waveform
      - '{{ inputs.stage }}'
    pipe_from: phonon
output: 'Generated pronunciation WAV and waveform MP4.'
YAML
"$stdo_bin" run -f "$stage/workflow.yaml" -i "stage=$stage" --no-cache --telemetry
# Publish only after every step, including Phonon, has succeeded.
mv -f "$stage/stdo-pronunciation.wav" assets/stdo-pronunciation.wav
mv -f "$stage/stdo-pronunciation.mp4" assets/stdo-pronunciation.mp4
wc -c assets/stdo-pronunciation.{wav,mp4}
