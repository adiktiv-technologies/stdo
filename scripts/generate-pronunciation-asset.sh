#!/usr/bin/env bash
# Dogfood the gallery: real Gemma 4 -> Phonon -> atomic WAV + waveform MP4.
set -euo pipefail
cd "$(dirname "$0")/.."
export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
stdo_bin=${STDO_BIN:-./target/release/stdo}
if [[ ! -x "$stdo_bin" ]]; then
  cargo build --locked --release
fi
command -v ollama >/dev/null
command -v ffmpeg >/dev/null
mkdir -p assets
"$stdo_bin" run -t -f examples/10-youtube-capsule-generator.yaml --no-cache \
  -i output_wav=assets/stdo-pronunciation.wav \
  -i output_mp4=assets/stdo-pronunciation.mp4 \
  -i llm_model=gemma4 \
  -i tts_model=phonon:latest \
  -i 'topic=For this pronunciation Easter egg, override the usual three-sentence format: write exactly two witty, self-aware spoken sentences, plain text only. In the first sentence riff on how nobody knows whether this tool is pronounced S. T. D. O. or studio, while every local AI model calls it steedo. Finish with this exact second sentence, with nothing after it: By the way, this audio was generated by a pipeline in S. T. D. O. ... I mean steedo ... wait, no, studio!'
